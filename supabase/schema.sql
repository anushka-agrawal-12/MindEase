-- MindEase schema for Supabase Postgres.
-- RLS is on with no policies: the public Supabase API cannot read these tables;
-- only the MindEase server (direct database connection) can.
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TEXT NOT NULL,
  gratitude_json TEXT NOT NULL DEFAULT '[]',
  saved_json TEXT NOT NULL DEFAULT '[]',
  remind_json TEXT NOT NULL DEFAULT '{}',
  extra_json TEXT NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS mood_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  mood_key TEXT NOT NULL,
  note TEXT,
  energy INTEGER NOT NULL,
  logged_at TEXT NOT NULL,
  tags TEXT NOT NULL DEFAULT '[]'
);
CREATE INDEX IF NOT EXISTS idx_mood_user ON mood_logs(user_id);
CREATE TABLE IF NOT EXISTS journal_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  entry_date TEXT NOT NULL,
  text TEXT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE(user_id, entry_date)
);
CREATE TABLE IF NOT EXISTS shares (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  keeper_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
  code TEXT UNIQUE,
  label TEXT NOT NULL DEFAULT '',
  scope_json TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  created_at TEXT NOT NULL,
  accepted_at TEXT,
  last_viewed_at TEXT,
  views INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_shares_owner ON shares(owner_id);
CREATE INDEX IF NOT EXISTS idx_shares_keeper ON shares(keeper_id);
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE mood_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE journal_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE shares ENABLE ROW LEVEL SECURITY;
CREATE TABLE IF NOT EXISTS auth_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bucket TEXT NOT NULL,
  at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_auth_attempts ON auth_attempts(bucket, at);
ALTER TABLE auth_attempts ENABLE ROW LEVEL SECURITY;
