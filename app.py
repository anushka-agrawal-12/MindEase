def _secret_key() -> str:
    """A random key kept in data/secret.key so sign-ins survive restarts."""
    env = os.environ.get("MINDEASE_SECRET")
    if env:
        return env
    f = DATA / "secret.key"
    if not f.exists():
        f.write_text(secrets.token_hex(32))
        try:
            f.chmod(0o600)
        except OSError:
            pass
    return f.read_text().strip()


