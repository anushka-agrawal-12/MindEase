class Conn:
    """Small wrapper so the rest of the code works the same on SQLite and Postgres."""

    def __init__(self, raw):
        self.raw = raw

    @staticmethod
    def _sql(sql):
        return sql.replace("?", "%s") if USE_PG else sql

    def execute(self, sql, params=()):
        return self.raw.execute(self._sql(sql), params)

    def executemany(self, sql, seq):
        if USE_PG:
            cur = self.raw.cursor()
            cur.executemany(self._sql(sql), seq)
            return cur
        return self.raw.executemany(sql, seq)

    def insert(self, sql, params=()):
        """INSERT and return the new row id."""
        if USE_PG:
            return self.raw.execute(self._sql(sql) + " RETURNING id", params).fetchone()["id"]
        return self.raw.execute(sql, params).lastrowid

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def connect() -> Conn:
    if USE_PG:
        # prepare_threshold=None keeps this working behind Supabase's connection pooler
        return Conn(psycopg.connect(DATABASE_URL, row_factory=dict_row, prepare_threshold=None, connect_timeout=10))
    raw = sqlite3.connect(DB_PATH, timeout=10)
    raw.row_factory = sqlite3.Row
    raw.execute("PRAGMA foreign_keys = ON")
    raw.execute("PRAGMA journal_mode = WAL")
    raw.execute("PRAGMA busy_timeout = 10000")
    return Conn(raw)


# ── database ──────────────────────────────────────────────────
def db() -> Conn:
    if "db" not in g:
        g.db = connect()
        if not USE_PG:
            g.db.raw.executescript(SCHEMA)  # harmless when the tables exist; recreates them if data/ was wiped
            _migrate(g.db.raw)
    return g.db


@app.teardown_appcontext
def close_db(_exc):
    conn = g.pop("db", None)
    if conn is not None:
        conn.close()


def _migrate(conn):
    """Adds columns that older databases do not have yet."""
    def cols(table):
        return {r[1] for r in conn.execute(f"PRAGMA table_info({table})")}
    if "tags" not in cols("mood_logs"):
        conn.execute("ALTER TABLE mood_logs ADD COLUMN tags TEXT NOT NULL DEFAULT '[]'")
    if "extra_json" not in cols("users"):
        conn.execute("ALTER TABLE users ADD COLUMN extra_json TEXT NOT NULL DEFAULT '{}'")
    conn.commit()


def init_db():
    conn = connect()
    if USE_PG:
        conn.execute(PG_SCHEMA)
        conn.commit()
    else:
        conn.raw.executescript(SCHEMA)
        _migrate(conn.raw)
    conn.close()


init_db()


