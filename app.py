# very small sign-in rate limit: 8 failures per 10 minutes per address + email
_fails = {}


def client_ip():
    """The real visitor address. Behind the Cloudflare Worker proxy it arrives in a header that is
    trusted only when it carries the shared MINDEASE_PROXY_KEY, so nobody can fake it."""
    key = os.environ.get("MINDEASE_PROXY_KEY")
    if key and secrets.compare_digest(request.headers.get("X-MindEase-Proxy-Key", ""), key):
        return request.headers.get("X-MindEase-Client", "")[:64] or request.remote_addr
    return request.remote_addr


def _bucket(email):
    return f"{client_ip()}|{email}"


def _too_many(email):
    now = time.time()
    hits = [t for t in _fails.get(_bucket(email), []) if now - t < 600]
    _fails[_bucket(email)] = hits
    return len(hits) >= 8


def _record_fail(email):
    _fails.setdefault(_bucket(email), []).append(time.time())


@app.after_request
def security_headers(resp):
    resp.headers.setdefault("X-Content-Type-Options", "nosniff")
    resp.headers.setdefault("X-Frame-Options", "DENY")
    resp.headers.setdefault("Referrer-Policy", "same-origin")
    resp.headers.setdefault("Permissions-Policy", "camera=(), microphone=(), geolocation=()")
    resp.headers.setdefault(
        "Content-Security-Policy",
        "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; "
        "font-src 'self'; connect-src 'self'; object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'",
    )
    if os.environ.get("MINDEASE_HTTPS") == "1":
        resp.headers.setdefault("Strict-Transport-Security", "max-age=31536000; includeSubDomains")
    if request.path.startswith("/api/"):
        resp.headers["Cache-Control"] = "no-store"  # personal data is never cached
    elif request.path in ("/", "/app", "/sw.js", "/manifest.webmanifest"):
        resp.headers["Cache-Control"] = "no-cache"
    return resp


