@app.post("/api/share/accept")
def share_accept():
    u = current_user()
    if not u:
        return error("Please sign in first.", 401)
    key = "accept"
    if _too_many(key):
        return error("Too many tries. Please wait a few minutes.", 429)
    code = re.sub(r"[^A-Za-z0-9]", "", str((request.get_json(silent=True) or {}).get("code") or "")).upper()
    r = db().execute("SELECT * FROM shares WHERE code = ? AND status = 'pending'", (code,)).fetchone() if code else None
    if not r or r["created_at"] < (_now() - timedelta(days=INVITE_DAYS)).isoformat():
        _record_fail(key)
        return error("That code did not work. It may have expired. Ask them for a new one.", 400)
    if r["owner_id"] == u["id"]:
        return error("That is your own code. Send it to the person who will keep an eye on you.", 400)
    dup = db().execute("SELECT 1 FROM shares WHERE owner_id = ? AND keeper_id = ? AND status = 'active'", (r["owner_id"], u["id"])).fetchone()
    if dup:
        return error("You already look after this person.", 400)
    db().execute("UPDATE shares SET keeper_id = ?, status = 'active', code = NULL, accepted_at = ? WHERE id = ?",
                 (u["id"], _now().isoformat(), r["id"]))
    db().commit()
    return jsonify({"ok": True})


def _streak(days):
    d, n = datetime.now().date(), 0
    if d.isoformat() not in days:
        d -= timedelta(days=1)
    while d.isoformat() in days:
        n += 1
        d -= timedelta(days=1)
    return n


def _alerts(logs):
    """Gentle, factual flags for a keeper. logs are newest first."""
    out = []
    if not logs:
        return out
    last = datetime.fromisoformat(logs[0]["t"].replace("Z", "+00:00"))
    quiet = (_now() - last).days
    if quiet >= 2:
        out.append({"kind": "quiet", "text": f"No check-in for {quiet} days."})
    recent = logs[:5]
    if len(recent) >= 3 and sum(1 for l in recent if l["k"] in HEAVY) >= 3:
        out.append({"kind": "heavy", "text": "Most of the last few check-ins have felt heavy."})
    low = logs[:3]
    if len(low) == 3 and sum(l["energy"] for l in low) / 3 <= 3:
        out.append({"kind": "energy", "text": "Energy has been low in the last few check-ins."})
    return out


@app.get("/api/keeper/people")
def keeper_people():
    u = current_user()
    if not u:
        return error("Please sign in first.", 401)
    rows = db().execute(
        "SELECT s.id, s.scope_json, s.accepted_at, o.id AS oid, o.name FROM shares s JOIN users o ON o.id = s.owner_id "
        "WHERE s.keeper_id = ? AND s.status = 'active' ORDER BY s.id DESC", (u["id"],)).fetchall()
    people = []
    for r in rows:
        sc = _scope(_loads(r["scope_json"], {}))
        logs = [{"k": x["mood_key"], "energy": x["energy"], "t": x["logged_at"]} for x in db().execute(
            "SELECT mood_key, energy, logged_at FROM mood_logs WHERE user_id = ? ORDER BY logged_at DESC LIMIT 5", (r["oid"],))]
        people.append({"id": r["id"], "name": r["name"], "lastCheckin": logs[0]["t"] if logs and sc["moods"] else None,
                       "lastMood": logs[0]["k"] if logs and sc["moods"] else None,
                       "alerts": _alerts(logs) if sc["alerts"] else [], "since": r["accepted_at"]})
    return jsonify({"people": people})


@app.get("/api/keeper/<int:sid>")
def keeper_view(sid):
    u = current_user()
    if not u:
        return error("Please sign in first.", 401)
    r = db().execute(
        "SELECT s.*, o.name AS oname, o.extra_json AS oextra FROM shares s JOIN users o ON o.id = s.owner_id "
        "WHERE s.id = ? AND s.keeper_id = ? AND s.status = 'active'", (sid, u["id"])).fetchone()
    if not r:
        return error("Not found.", 404)
    sc = _scope(_loads(r["scope_json"], {}))
    oid = r["owner_id"]
    all_logs = [{"k": x["mood_key"], "note": x["note"] or "", "energy": x["energy"], "t": x["logged_at"], "tags": _loads(x["tags"], [])}
                for x in db().execute("SELECT * FROM mood_logs WHERE user_id = ? ORDER BY logged_at DESC", (oid,))]
    since = (_now() - timedelta(days=90)).isoformat()
    logs = []
    if sc["moods"]:
        for l in all_logs:
            if l["t"] < since:
                continue
            item = {"k": l["k"], "energy": l["energy"], "t": l["t"]}
            if sc["tags"]:
                item["tags"] = l["tags"]
            if sc["notes"]:
                item["note"] = l["note"]
            logs.append(item)
    journal = {}
    if sc["journal"]:
        for x in db().execute("SELECT entry_date, text FROM journal_entries WHERE user_id = ? ORDER BY entry_date DESC LIMIT 30", (oid,)):
            journal[x["entry_date"]] = x["text"]
    daily = None
    if sc["daily"]:
        d = _loads(r["oextra"], {}).get("daily")
        if isinstance(d, dict) and isinstance(d.get("done"), dict):
            tasks = [t for t in (d.get("tasks") or []) if isinstance(t, dict) and t.get("on", True)]
            daily = {"total": len(tasks), "done": {k: len(v) for k, v in list(d["done"].items())[-60:] if isinstance(v, list) and DATE.match(str(k))}}
    days = {l["t"][:10] for l in all_logs}
    db().execute("UPDATE shares SET last_viewed_at = ?, views = views + 1 WHERE id = ?", (_now().isoformat(), sid))
    db().commit()
    return jsonify({
        "name": r["oname"], "scope": sc, "logs": logs, "journal": journal, "daily": daily,
        "streak": _streak(days) if sc["moods"] else None, "total": len(all_logs) if sc["moods"] else None,
        "alerts": _alerts(all_logs) if sc["alerts"] else [],
    })


@app.delete("/api/keeper/<int:sid>")
def keeper_leave(sid):
    """A keeper can step away at any time."""
    u = current_user()
    if not u:
        return error("Please sign in first.", 401)
    cur = db().execute("DELETE FROM shares WHERE id = ? AND keeper_id = ?", (sid, u["id"]))
    db().commit()
    return jsonify({"ok": True}) if cur.rowcount else error("Not found.", 404)


