    label = str(body["label"]).strip()[:40] if isinstance(body.get("label"), str) else r["label"]
    db().execute("UPDATE shares SET scope_json = ?, label = ? WHERE id = ?", (json.dumps(scope), label, sid))
    db().commit()
    return jsonify({"ok": True})


