@app.post("/api/auth/register")
def register():
    body = request.get_json(silent=True) or {}
    email = str(body.get("email") or "").strip().lower()
    password = str(body.get("password") or "")
    name = str(body.get("name") or "").strip()
    if len(email) > 254 or not EMAIL.match(email):
        return error("Please enter a valid email address.", 400)
    if len(password) < 8:
        return error("Password needs at least 8 characters.", 400)
    if len(password) > 128:
        return error("Password is too long (128 characters max).", 400)
    if _too_many("register"):
        return error("Too many tries. Please wait a few minutes and try again.", 429)
    _record_fail("register")  # counts every sign-up attempt from this address
    if not name:
        name = email.split("@")[0]
    name = name[:60]
    try:
        new_id = db().insert(
            "INSERT INTO users (email, name, password_hash, created_at) VALUES (?, ?, ?, ?)",
            (email, name, generate_password_hash(password), datetime.now(timezone.utc).isoformat()),
        )
        db().commit()
    except INTEGRITY:
        db().rollback()
        return error("An account with this email already exists. Try signing in.", 400)
    start_session(new_id)
    return jsonify({"signedIn": True, "name": name, "email": email})


@app.post("/api/auth/login")
def login():
    body = request.get_json(silent=True) or {}
    email = str(body.get("email") or "").strip().lower()
    password = str(body.get("password") or "")
    if _too_many(email):
        return error("Too many tries. Please wait a few minutes and try again.", 429)
    u = db().execute("SELECT * FROM users WHERE email = ?", (email,)).fetchone()
    # same message and similar timing whether or not the email exists
    ok = check_password_hash(u["password_hash"] if u else DUMMY_HASH, password)
    if not u or not ok:
        _record_fail(email)
        return error("That email and password do not match.", 401)
    start_session(u["id"])
    return jsonify(user_json(u))


